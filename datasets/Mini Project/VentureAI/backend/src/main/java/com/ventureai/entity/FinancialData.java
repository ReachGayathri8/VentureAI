package com.ventureai.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;

@Entity
@Table(name = "financial_data")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class FinancialData {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @OneToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "startup_id", nullable = false, unique = true)
    @JsonIgnore
    private Startup startup;

    // ============================================================
    // FUNDING
    // ============================================================

    /**
     * Total initial capital available to start the business.
     *
     * Used as a fallback when founderInvestment and externalFunding
     * are not separately provided.
     */
    @Builder.Default
    private BigDecimal initialInvestment = BigDecimal.ZERO;

    /**
     * Capital contributed by founders.
     * Treated as equity.
     */
    @Builder.Default
    private BigDecimal founderInvestment = BigDecimal.ZERO;

    /**
     * External funding received by the startup.
     *
     * NOTE:
     * Until financingType is added to the database, the finance
     * engine treats this as external financing rather than assuming
     * it is definitely a loan.
     */
    @Builder.Default
    private BigDecimal externalFunding = BigDecimal.ZERO;

    /**
     * Type of external funding.
     *
     * Examples:
     * EQUITY
     * DEBT
     * GRANT
     * OTHER
     *
     * Stored as String to avoid breaking existing database/data
     * during the first migration.
     */
    @Builder.Default
    private String financingType = "EQUITY";


    // ============================================================
    // RECURRING OPERATING COSTS
    // ============================================================

    /**
     * Total monthly operating cost.
     *
     * Used when detailed expense categories are unavailable.
     */
    @Builder.Default
    private BigDecimal monthlyOperatingCost = BigDecimal.ZERO;

    /**
     * Monthly employee/payroll cost.
     */
    @Builder.Default
    private BigDecimal employeeCost = BigDecimal.ZERO;

    /**
     * Monthly marketing expense.
     */
    @Builder.Default
    private BigDecimal marketingCost = BigDecimal.ZERO;

    /**
     * Recurring infrastructure/software/platform cost.
     */
    @Builder.Default
    private BigDecimal infrastructureCost = BigDecimal.ZERO;

    /**
     * Product development expense.
     *
     * This should represent recurring development expense.
     * One-time CAPEX should be entered separately below.
     */
    @Builder.Default
    private BigDecimal productDevelopmentCost = BigDecimal.ZERO;


    // ============================================================
    // CUSTOMER & REVENUE ASSUMPTIONS
    // ============================================================

    /**
     * Expected number of customers/orders/units in Month 1.
     *
     * Interpretation depends on the business model.
     */
    @Builder.Default
    private Integer expectedMonthlyCustomers = 0;

    /**
     * Average revenue generated by one customer/order/unit.
     */
    @Builder.Default
    private BigDecimal averageCustomerRevenue = BigDecimal.ZERO;

    /**
     * Expected annual customer/revenue growth rate.
     *
     * Example:
     * 20 means 20% annual growth.
     *
     * This is a BUSINESS ASSUMPTION, not industry CAGR.
     */
    @Builder.Default
    private Double expectedGrowthRate = 0.0;

    /**
     * Number of years to project.
     */
    @Builder.Default
    private Integer projectionPeriodYears = 3;


    // ============================================================
    // UNIT ECONOMICS
    // ============================================================

    /**
     * Selling price per unit/order.
     *
     * For subscription businesses this can represent
     * average monthly subscription revenue.
     */
    @Builder.Default
    private BigDecimal sellingPricePerUnit = BigDecimal.ZERO;

    /**
     * Direct variable cost per unit/order.
     *
     * Examples:
     * - raw material
     * - packaging
     * - payment processing
     * - delivery cost
     * - transaction fees
     */
    @Builder.Default
    private BigDecimal variableCostPerUnit = BigDecimal.ZERO;

    /**
     * Monthly fixed costs used for break-even.
     *
     * If zero, the Finance Engine derives fixed costs
     * from available operating-cost fields.
     */
    @Builder.Default
    private BigDecimal fixedCosts = BigDecimal.ZERO;


    // ============================================================
    // CUSTOMER ACQUISITION
    // ============================================================

    /**
     * Monthly new customers acquired.
     *
     * If zero, the Finance Engine can derive customer growth
     * from the expected growth assumption.
     */
    @Builder.Default
    private Integer monthlyNewCustomers = 0;

    /**
     * Customer acquisition cost.
     *
     * CAC =
     * Sales & marketing acquisition spend /
     * number of newly acquired customers
     */
    @Builder.Default
    private BigDecimal customerAcquisitionCost = BigDecimal.ZERO;

    /**
     * Monthly customer churn percentage.
     *
     * Example:
     * 5 = 5% of existing customers leave per month.
     */
    @Builder.Default
    private Double monthlyChurnRate = 0.0;


    // ============================================================
    // CUSTOMER VALUE
    // ============================================================

    /**
     * Average number of months a customer remains active.
     *
     * Used for LTV estimation when explicitly provided.
     */
    @Builder.Default
    private Double averageCustomerLifetimeMonths = 0.0;


    // ============================================================
    // TAX
    // ============================================================

    /**
     * Estimated effective tax rate.
     *
     * Example:
     * 25 = 25%.
     *
     * Zero means tax is not modeled because the user has not
     * supplied a tax assumption.
     */
    @Builder.Default
    private Double taxRate = 0.0;


    // ============================================================
    // CAPITAL EXPENDITURE
    // ============================================================

    /**
     * One-time capital expenditure.
     *
     * Examples:
     * - equipment
     * - machinery
     * - computers
     * - furniture
     *
     * This is different from recurring infrastructure expense.
     */
    @Builder.Default
    private BigDecimal capitalExpenditure = BigDecimal.ZERO;

    /**
     * Estimated useful life of CAPEX in months.
     *
     * Used for depreciation if supplied.
     */
    @Builder.Default
    private Integer assetUsefulLifeMonths = 0;


    // ============================================================
    // DEBT
    // ============================================================

    /**
     * Outstanding debt principal.
     *
     * Used only when financingType = DEBT.
     */
    @Builder.Default
    private BigDecimal debtAmount = BigDecimal.ZERO;

    /**
     * Annual interest rate on debt.
     *
     * Example:
     * 12 = 12% per year.
     */
    @Builder.Default
    private Double annualInterestRate = 0.0;

    /**
     * Debt repayment period in months.
     */
    @Builder.Default
    private Integer debtTermMonths = 0;


    // ============================================================
    // WORKING CAPITAL
    // ============================================================

    /**
     * Percentage of monthly revenue expected to remain
     * outstanding as accounts receivable.
     *
     * Example:
     * 10 = 10%.
     */
    @Builder.Default
    private Double accountsReceivableRate = 0.0;

    /**
     * Percentage of monthly operating costs purchased
     * on credit.
     *
     * Example:
     * 20 = 20%.
     */
    @Builder.Default
    private Double accountsPayableRate = 0.0;

    /**
     * Inventory holding amount as a percentage of
     * monthly COGS.
     *
     * Example:
     * 15 = 15%.
     */
    @Builder.Default
    private Double inventoryRate = 0.0;


    // ============================================================
    // CASH RESERVE
    // ============================================================

    /**
     * Minimum cash reserve the startup wants to maintain.
     *
     * Useful for runway/risk analysis.
     */
    @Builder.Default
    private BigDecimal minimumCashReserve = BigDecimal.ZERO;
}
